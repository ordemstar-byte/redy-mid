// ALGORITMO DE BUSCA INTELIGENTE COM TOLERÂNCIA A ERROS FONÉTICOS E DIGITAÇÃO
// ============================================================================

function normalize(str: string): string {
  let s = (str || '')
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .trim()

  // Mapeamento de sinônimos e erros fonéticos frequentes
  s = s.replace(/\bbraddesco\b/g, 'bradesco')
  s = s.replace(/\bbradescard\b/g, 'bradesco')
  s = s.replace(/\bpickpay\b/g, 'picpay')
  s = s.replace(/\bpic\s+pay\b/g, 'picpay')
  s = s.replace(/\bitaucard\b/g, 'itau')
  s = s.replace(/\bitau\s+card\b/g, 'itau')
  s = s.replace(/\bsatander\b/g, 'santander')
  s = s.replace(/\bcefc?\b/g, 'caixa')
  s = s.replace(/\bbancodobrasil\b/g, 'banco do brasil')
  s = s.replace(/\bdux\b/g, 'brb dux')
  s = s.replace(/\bassai\b/g, 'passai')
  s = s.replace(/\bpda\b/g, 'pao de acucar')

  return s
}

/**
 * Busca inteligente de cartões no catálogo por texto livre.
 * Suporta busca por banco (Itaú, Bradesco, Safra, PicPay...),
 * modelo (Click, Neo, SX, Like, TPC, Infinite, Black...),
 * bandeira e classe.
 */
export function searchCardPresets(query: string, bankFilter?: string): CardPresetItem[] {
  let list = CARD_PRESETS_CATALOG

  // Filtro prévio por banco se selecionado
  if (bankFilter && bankFilter !== 'all') {
    const bf = normalize(bankFilter)
    list = list.filter((item) => normalize(item.bank).includes(bf))
  }

  const q = normalize(query)
  if (!q) {
    return list
  }

  const terms = q.split(/\s+/).filter(Boolean)

  return list.filter((item) => {
    const itemTarget = normalize(
      `${item.name} ${item.bank} ${item.brand} ${item.tierLabel} ${item.keywords.join(' ')} ${item.notes || ''}`
    )
    return terms.every((term) => itemTarget.includes(term))
  })
}

/**
 * Detecção automática com base no que o usuário digita no input.
 */
export function autoDetectCardPreset(input: string): CardPresetItem | null {
  const matches = searchCardPresets(input)
  if (matches.length > 0) {
    return matches[0]
  }
  return null
}
